"""
RF-16.7 access-control tests for student PDF downloads.

RF-16.7 mandates **temporary URLs with short expiration and simple
encryption of the PDF in transit, derived from the user's session
identifier**, plus the cessation of access once the review window
closes. The current implementation:

- Composes the PDF on each request from MinIO and streams the bytes
  through the Django view (``InstanceDownloadView``). MinIO presigned
  URLs are generated by ``apps.exams.services.storage.generate_presigned_url``
  but are only used for the manager's instrumented-PDF download —
  the student flow never sees them.
- Does not encrypt the PDF in transit beyond TLS at the edge.
- Does not check the instance's status nor the exam's
  ``student_permissions.can_view_pages_after_review`` when the
  student fetches their own PDF.

References: RF-16.7, RF-12.x.
"""

